test("4. Delete action removes draft row and cannot delete approved story", async () => {
  const draftRow: MockMapStory = {
    id: 1395,
    type: "weather",
    target_id: "Godavari–Krishna mangroves",
    language: "ru",
    content: "Черновик мангров...",
    is_approved: false,
    auto_generated: true,
    auto_generation_model: "antigravity-ide",
    created_at: "2026-08-06T14:00:00Z",
  };

  const approvedRow: MockMapStory = {
    id: 9999,
    type: "river",
    target_id: "Nile",
    language: "ru",
    content: "Утвержденный Нил...",
    is_approved: true,
    auto_generated: true,
    auto_generation_model: "antigravity-ide",
    created_at: "2026-08-06T14:00:00Z",
  };

  const supabase = createMockSupabaseWithStories([draftRow, approvedRow]);

  // Attempt to delete approved story (must fail)
  await supabase
    .from("map_stories")
    .delete()
    .eq("id", 9999)
    .eq("is_approved", false)
    .eq("auto_generated", true);

  assert.equal(supabase._getDb().some((r) => r.id === 9999), true);

  // Delete draft story (must succeed)
  await supabase
    .from("map_stories")
    .delete()
    .eq("id", 1395)
    .eq("is_approved", false)
    .eq("auto_generated", true);

  assert.equal(supabase._getDb().some((r) => r.id === 1395), false);
});

test("5. Batch approval handles partial success gracefully", async () => {
  const rows: MockMapStory[] = [
    {
      id: 1393,
      type: "sea",
      target_id: "Bransfield Strait",
      language: "ru",
      content: "...",
      is_approved: false,
      auto_generated: true,
      auto_generation_model: "antigravity-ide",
      created_at: "2026-08-06T14:00:00Z",
    },
    {
      id: 1394,
      type: "physic",
      target_id: "Island Mafia I.",
      language: "ru",
      content: "...",
      is_approved: false,
      auto_generated: true,
      auto_generation_model: "antigravity-ide",
      created_at: "2026-08-06T14:00:00Z",
    },
    {
      id: 9999, // Already approved
      type: "river",
      target_id: "AlreadyApproved",
      language: "ru",
      content: "...",
      is_approved: true,
      auto_generated: true,
      auto_generation_model: "antigravity-ide",
      created_at: "2026-08-06T14:00:00Z",
    },
  ];

  const supabase = createMockSupabaseWithStories(rows);

  const idsToApprove = [1393, 1394, 9999];
  let approvedCount = 0;
  let failedCount = 0;

  for (const id of idsToApprove) {
    const { data: res } = await supabase
      .from("map_stories")
      .update({ is_approved: true })
      .eq("id", id)
      .eq("is_approved", false)
      .eq("auto_generated", true);

    if (res && res.length > 0) {
      approvedCount += 1;
    } else {
      failedCount += 1;
    }
  }

  assert.equal(approvedCount, 2);
  assert.equal(failedCount, 1);
});
