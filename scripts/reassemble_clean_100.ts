async function reassembleClean() {
  loadEnvLocal();

  const url = process.env.SUPABASE_URL || process.env.NEXT_PUBLIC_SUPABASE_URL;
  const key = process.env.SUPABASE_SERVICE_ROLE_KEY || process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY;

  if (!url || !key) {
    console.error("Missing Supabase credentials");
    process.exit(1);
  }

  const supabase = createClient(url, key);

  console.log("================================================================================");
  console.log("🚀 RE-ASSEMBLING CLEAN 100-ITEM CANDIDATE PACKAGE (STRICTLY ABSENT TARGETS)");
  console.log("================================================================================");

  // 1. Fetch ALL existing RU map_stories using paginated queries
  let allRuStories: Array<{ type: string; target_id: string }> = [];
  let page = 0;
  const pageSize = 1000;
  let hasMore = true;

  while (hasMore) {
    const { data: pageData, error } = await supabase
      .from("map_stories")
      .select("type, target_id, language")
      .eq("language", "ru")
      .range(page * pageSize, (page + 1) * pageSize - 1);

    if (error || !pageData || pageData.length === 0) {
      hasMore = false;
    } else {
      allRuStories = allRuStories.concat(pageData);
      if (pageData.length < pageSize) {
        hasMore = false;
      } else {
        page++;
      }
    }
  }

  const dbRuSet = new Set(allRuStories.map((s) => `${s.type}:${s.target_id}`));
  console.log(`Paginated DB Query: Total RU stories in map_stories = ${dbRuSet.size}`);

  // 2. Load previous 100 candidates & filter out duplicates
  const candidateFile = path.join(process.cwd(), ".pilot-reports/candidate-100-stories-latest.json");
  const rawCandidates: CandidateStory[] = JSON.parse(fs.readFileSync(candidateFile, "utf-8"));

  const validNewCandidates = rawCandidates.filter((c) => !dbRuSet.has(`${c.map_type}:${c.target_id}`));
  console.log(`Kept ${validNewCandidates.length} truly absent candidates from previous batch.`);

  // 3. Fetch additional unwritten targets from map_targets to reach exactly 100 items
  const neededCount = 100 - validNewCandidates.length;
  console.log(`Need ${neededCount} additional unwritten targets to reach 100 clean items.`);

  const { data: allTargets } = await supabase
    .from("map_targets")
    .select("map_type, target_id, title_ru, title_en");

  const unwrittenTargets = (allTargets || []).filter((t) => !dbRuSet.has(`${t.map_type}:${t.target_id}`));
  
  // Filter out targets already in validNewCandidates
  const currentCandidateSet = new Set(validNewCandidates.map((c) => `${c.map_type}:${c.target_id}`));
  const freshTargets = unwrittenTargets.filter((t) => !currentCandidateSet.has(`${t.map_type}:${t.target_id}`));

  console.log(`Found ${freshTargets.length} fresh unwritten targets in map_targets table.`);

  const selectedExtraTargets = freshTargets.slice(0, neededCount);

  // 4. Generate story content for extra targets
  const extraCandidates: CandidateStory[] = selectedExtraTargets.map((t) => {
    const story = extraStories[t.target_id];
    if (!story) {
      throw new Error(`Missing story template for extra target_id: "${t.target_id}"`);
    }
    return {
      map_type: t.map_type,
      target_id: t.target_id,
      content: story,
    };
  });

  const finalClean100 = [...validNewCandidates, ...extraCandidates];
  console.log(`\nFinal Clean Package Assembled: ${finalClean100.length} items.`);

  // 5. Run full output validation against Definition of Done
  const validation = validatePilotOutput(
    JSON.stringify(finalClean100, null, 2),
    finalClean100.map((c) => ({ target_id: c.target_id, map_type: c.map_type }))
  );

  console.log("--------------------------------------------------------------------------------");
  console.log("VALIDATION RESULTS FOR RE-ASSEMBLED CLEAN PACKAGE:");
  console.log(`- Is Valid Output: ${validation.isValid ? "YES (100% PASS)" : "NO"}`);
  console.log(`- Valid Objects Count: ${validation.validObjectsCount} / ${finalClean100.length}`);
  console.log(`- Errors Count: ${validation.errors.length}`);
  console.log(`- Warnings Count: ${validation.warnings.length}`);
  console.log("--------------------------------------------------------------------------------");

  if (validation.errors.length > 0) {
    console.error("❌ VALIDATION ERRORS:");
    validation.errors.forEach((e) => console.error(`  - ${e}`));
    process.exit(1);
  }

  // 6. Verify exact read-only absence of every item in finalClean100
  let doubleCheckDuplicates = 0;
  for (const c of finalClean100) {
    const { data: dbMatch } = await supabase
      .from("map_stories")
      .select("id")
      .eq("type", c.map_type)
      .eq("target_id", c.target_id)
      .eq("language", "ru");

    if (dbMatch && dbMatch.length > 0) {
      console.error(`DOUBLE CHECK FAILED for target_id: "${c.target_id}"`);
      doubleCheckDuplicates++;
    }
  }

  console.log(`Double-check against map_stories: ${doubleCheckDuplicates} duplicates found.`);

  if (doubleCheckDuplicates === 0) {
    // Save clean 100 candidates file
    const reportsDir = path.join(process.cwd(), ".pilot-reports");
    const timestamp = new Date().toISOString().replace(/[:.]/g, "-");
    const cleanPath = path.join(reportsDir, `candidate-100-stories-clean-${timestamp}.json`);
    const latestPath = path.join(reportsDir, "candidate-100-stories-latest.json");

    fs.writeFileSync(cleanPath, JSON.stringify(finalClean100, null, 2), "utf-8");
    fs.writeFileSync(latestPath, JSON.stringify(finalClean100, null, 2), "utf-8");

    console.log(`✅ SUCCESS! Clean 100-item Candidate package saved to:`);
    console.log(`   - ${cleanPath}`);
    console.log(`   - ${latestPath}`);
  }

  console.log("================================================================================\n");
}

